/**
 * Builds public/icons.svg: one <symbol> per lucide-react icon used by server components.
 *
 * Server components render <Icon> from src/components/ui/icons.tsx, which is a 2-node
 * <svg><use href="/icons.svg#Name"/></svg>. That keeps each icon out of the RSC payload and
 * out of hydration, while the artwork is still lucide-react's own (rendered here).
 *
 * Icon names are read from the spriteIcon("Name") calls in icons.tsx, so that file is the
 * only list to maintain. Runs automatically before `pnpm dev` and `pnpm build`.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";

const root = fileURLToPath(new URL("..", import.meta.url));
const registry = readFileSync(`${root}src/components/ui/icons.tsx`, "utf8");
const names = [...registry.matchAll(/^export const \w+ = spriteIcon\("(\w+)"\);$/gm)].map(
  (m) => m[1],
);

if (names.length === 0) throw new Error("No spriteIcon(...) calls found in icons.tsx");

const symbols = names.map((name) => {
  const Icon = lucide[name];
  if (!Icon) throw new Error(`lucide-react has no icon named ${name}`);
  const markup = renderToStaticMarkup(createElement(Icon));
  // Keep only the shapes; stroke, width, and caps come from the referencing <svg>.
  const inner = markup.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return `<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`;
const version = createHash("sha1").update(sprite).digest("hex").slice(0, 10);

writeFileSync(`${root}public/icons.svg`, sprite);
writeFileSync(
  `${root}src/components/ui/icon-sprite.generated.ts`,
  `// Generated by scripts/build-icon-sprite.mjs. Do not edit.\nexport const ICON_SPRITE_URL = "/icons.svg?v=${version}";\n`,
);
console.log(`icons.svg: ${names.length} icons, ${sprite.length} bytes, v=${version}`);
